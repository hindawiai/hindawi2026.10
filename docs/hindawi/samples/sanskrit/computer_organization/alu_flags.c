/* the ALU: eight-bit addition and subtraction with zero, sign, carry and overflow flags */
शून्य सञ्चालय(पूर्णाङ्क प्रथमम्, पूर्णाङ्क द्वितीयम्, पूर्णाङ्क व्यवकलय) {
  पूर्णाङ्क दक्षिण = व्यवकलय ? (~द्वितीयम् & 0xFF) : द्वितीयम्, योगः = प्रथमम् + दक्षिण + व्यवकलय;
  पूर्णाङ्क परिणामः = योगः & 0xFF, वाहः = योगः >> 8;
  पूर्णाङ्क अतिप्रवाहः = !((प्रथमम् ^ दक्षिण) & 0x80) && ((प्रथमम् ^ परिणामः) & 0x80);
  प्रारूप_लिख("%02X zero %d sign %d carry %d overflow %d\n", परिणामः, परिणामः == 0, परिणामः >> 7, वाहः, अतिप्रवाहः);
}
