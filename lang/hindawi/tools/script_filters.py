"""script_filters.py: the script filter in front of Romenagri, as the original pipeline has it.

Chintamani carries its own filters, fltr_te_hi (Telugu to Devanagari) and fltr_ur_hi (Urdu, and with it the
Perso-Arabic scripts, to Devanagari); they are used as they are. For the other Brahmi-derived scripts, a filter of the
same kind (flex, C, UTF-8 in and out) is generated here by Unicode name: BENGALI LETTER KA becomes DEVANAGARI LETTER KA.
Scripts with neither have no compilation path yet; they still ingest and read in full.

  python3 script_filters.py build             generate and build every filter into .build/filters/
  python3 script_filters.py which LANGUAGE    the filter a language's compilation path uses
"""
import json, os, subprocess, sys, unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
OUT = Path(os.environ.get("HINDAWI_FILTERS", REPO / ".build/filters"))
RMN = Path(os.environ.get("ROMENAGRI", REPO / ".build/chintamani/Romenagri"))
ORIGINAL = {"TELUGU": "fltr_te_hi", "ARABIC": "fltr_ur_hi"}          # Chintamani's own
PROJECTED = ["BENGALI", "GURMUKHI", "GUJARATI", "ORIYA", "TAMIL", "KANNADA", "MALAYALAM"]
BLOCK = {"BENGALI": 0x980, "GURMUKHI": 0xA00, "GUJARATI": 0xA80, "ORIYA": 0xB00, "TAMIL": 0xB80, "KANNADA": 0xC80,
         "MALAYALAM": 0xD00}


def script_of_language(lang):
    params = json.load(open(REPO / "lang/hindawi/pipeline/language_params.json", encoding="utf-8"))
    text = "".join(v.get("native", "") for v in params.get(lang, {}).values() if isinstance(v, dict))
    names = [unicodedata.name(c, "?").split(" ")[0] for c in text if ord(c) > 0x7F and c.isalpha()]
    return max(set(names), key=names.count) if names else "LATIN"


def lex(src, dst, pairs):
    rules = "\n".join('"%s"\t{ fputs("%s", yyout); }' % (a.encode("utf-8").decode("latin-1").replace("\\", "\\\\").replace('"', '\\"'),
                                                           "".join(f"\\x{b:02x}" for b in b.encode("utf-8")))
                      for a, b in sorted(pairs, key=lambda p: -len(p[0])))
    return (f"%{{\n/* fltr_{src}_{dst}: {src} to {dst} by Unicode name, in the form of Chintamani's fltr_te_hi.\n"
            f"   Generated by lang/hindawi/tools/script_filters.py. UTF-8 in, UTF-8 out. */\n#include <stdio.h>\n%}}\n"
            f"%option noyywrap 8bit\n%%\n{rules}\n.|\\n\t{{ ECHO; }}\n%%\nint main(void) {{ yylex(); return 0; }}\n")


# Gurmukhi names some signs differently from Devanagari; without these, the filter passed them through raw and Romenagri
# emitted control bytes. Addak (gemination) has no Devanagari sign and is dropped (DEVIATIONS.md).
ALIASES = {"GURMUKHI": [(" SIGN BINDI", " SIGN ANUSVARA"), (" TIPPI", " SIGN ANUSVARA"), (" VOWEL SIGN EE", " VOWEL SIGN E"),
                        (" VOWEL SIGN OO", " VOWEL SIGN O"), (" LETTER EE", " LETTER E"), (" LETTER OO", " LETTER O"),
                        (" ADDAK", None)]}


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    for s in PROJECTED:
        pairs = []
        for cp in range(BLOCK[s], BLOCK[s] + 0x80):
            c = chr(cp); n = unicodedata.name(c, "")
            if not n.startswith(s + " "):
                continue
            rest = n[len(s):]
            for alias, to in ALIASES.get(s, ()):       # the same letter under another Unicode name
                if rest.endswith(alias) and to is not None:
                    rest = rest[: -len(alias)] + to
                elif rest.endswith(alias):
                    rest = None                            # a sign Devanagari does not write: dropped
                    break
            if rest is None:
                pairs.append((c, ""))
                continue
            try:
                pairs.append((c, unicodedata.lookup("DEVANAGARI" + rest)))
            except KeyError:
                pass
        back = list({b: (b, a) for a, b in reversed(pairs) if b}.values())     # one source per Devanagari letter
        for name, ps in ((f"fltr_{s.lower()}_hi", pairs), (f"fltr_hi_{s.lower()}", back)):
            (OUT / f"{name}.lex").write_bytes(lex(s.lower(), "hi", ps).replace(f"fltr_{s.lower()}_hi", name).encode("latin-1"))
            r = subprocess.run(f"flex -8 -o '{OUT}/{name}.c' '{OUT}/{name}.lex' && gcc -O1 -o '{OUT}/{name}' '{OUT}/{name}.c'",
                               shell=True, capture_output=True, text=True)
            print(f"script_filters: {name} {'built' if r.returncode == 0 else 'FAILED ' + r.stderr[-200:]} ({len(ps)} characters)")


# Letters of Pashto, Sindhi and other Perso-Arabic orthographies that Chintamani's Urdu filter does not know, folded
# to the nearest Urdu letter before it; without this the filter emits control bytes for them (DEVIATIONS.md).
FOLD = str.maketrans({"ټ": "ٹ", "ډ": "ڈ", "ړ": "ڑ", "ږ": "ژ", "ښ": "ش", "ګ": "گ", "ڼ": "ن", "ې": "ی", "ۍ": "ی", "ځ": "ز",
                      "څ": "س", "ڪ": "ک", "ڳ": "گ", "ڱ": "نگ", "ڄ": "ج", "ٻ": "ب", "ڀ": "بھ", "ٽ": "ٹ", "ٿ": "تھ", "ڊ": "ڈ",
                      "ڏ": "د", "ڍ": "ڈھ", "ڙ": "ڑ", "ڦ": "پھ", "ڻ": "ن", "ڇ": "چھ", "ڌ": "دھ", "ۀ": "ہ"})


def fold(lang, text):
    """The text as Chintamani's Urdu filter can read it, for Perso-Arabic languages; unchanged for every other script."""
    return text.translate(FOLD) if script_of_language(lang) == "ARABIC" else text


def which(lang):
    """The filter's path, '' for Devanagari, or None when the script has no filter yet."""
    s = script_of_language(lang)
    if s == "DEVANAGARI":
        return ""
    if s in ORIGINAL and (RMN / ORIGINAL[s]).exists():
        return str(RMN / ORIGINAL[s])
    p = OUT / f"fltr_{s.lower()}_hi"
    if s in PROJECTED and not p.exists():
        build()
    return str(p) if p.exists() else None


def prepare(lang, text):
    """A transducer, filtered for its lexer. Some filters read a letter by its context (Perso-Arabic alef at the start
    of a line and after a space come out differently), so each keyword is filtered both ways and gets a rule for every
    form it can take in a program; everything else passes through the filter as the original Makefiles do."""
    import re
    f = which(lang)
    if not f:
        return text
    run = lambda t: subprocess.run(f"'{f}'", shell=True, input=fold(lang, t).encode("utf-8"), capture_output=True).stdout.decode("utf-8", "replace")
    rule = re.compile(r'^(\S+)(\s+)(\{\s*printf\("(?:[^"\\]|\\.)*"\);\s*\})\s*$')
    out = []
    for line in text.split("\n"):
        m = rule.match(line)
        if not m or not any(ord(c) > 0x7F for c in m.group(1)):
            out.append(run(line) if any(ord(c) > 0x7F for c in line) else line); continue
        word = re.sub(r"\\(.)", r"\1", m.group(1))
        forms = {run(word), run(" " + word).lstrip(" ")}
        for v in sorted(forms):
            out.append(re.sub(r'([\\"\[\](){}.*+?|^$/#%<>-])', r"\\\1", v) + m.group(2) + m.group(3))
    return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "prepare":
        sys.stdout.write(prepare(sys.argv[2], sys.stdin.read())); sys.exit(0)
    if len(sys.argv) > 1 and sys.argv[1] == "build":
        build()
    elif len(sys.argv) > 2 and sys.argv[1] == "which":
        w = which(sys.argv[2]); print(w if w is not None else f"no filter for {script_of_language(sys.argv[2])}"); sys.exit(0 if w is not None else 1)
    else:
        print(__doc__); sys.exit(2)
